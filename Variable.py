# Declaring variables of different data types

student_name = "saziya"      # String
student_age = 20                 # Integer
cgpa = 8.75                      # Float
is_student = True                # Boolean
favorite_subjects = ["Python", "Math", "IoT"]  # List
student_details = {
    "Roll No": 101,
    "Branch": "CSE"
}                                 

# Printing values and their data types

print("Student Name:", student_name)
print("Data Type:", type(student_name))

print("Student Age:", student_age)
print("Data Type:", type(student_age))

print("CGPA:", cgpa)
print("Data Type:", type(cgpa))

print("Is Student:", is_student)
print("Data Type:", type(is_student))

print("Favorite Subjects:", favorite_subjects)
print("Data Type:", type(favorite_subjects))

print("Student Details:", student_details)
print("Data Type:", type(student_details))